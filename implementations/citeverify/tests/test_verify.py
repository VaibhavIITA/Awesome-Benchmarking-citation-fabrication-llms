def test_cache_avoids_second_call(tmp_path):
    calls = []

    def g(url, params=None, timeout=None):
        calls.append(url)
        return fake_get(url, params, timeout)
    cl = Client(tmp_path, get=g, pause=0)
    cl.crossref("t", "a")
    cl.crossref("t", "a")
    assert len(calls) == 1


def test_retry_on_429(tmp_path, monkeypatch):
    seq = [Resp(429, None), Resp(200, CR_DATA)]
    monkeypatch.setattr("time.sleep", lambda s: None)
    cl = Client(tmp_path, get=lambda u, params=None, timeout=None: seq.pop(0), pause=0)
    assert cl.crossref("t", "a")[0]["surnames"] == ["walters", "wilder"]


def test_datacite_fallback_for_arxiv_doi(tmp_path):
    def g(url, params=None, timeout=None):
        if "datacite" in url:
            return Resp(200, {"data": {"attributes": {
                "titles": [{"title": "YOLOv3: An Incremental Improvement"}],
                "creators": [{"familyName": "Redmon"}, {"name": "Farhadi, Ali"}],
                "publicationYear": 2018}}})
        return Resp(404, None)        # CrossRef does not know arXiv DOIs
    r = Client(tmp_path, get=g, pause=0).by_doi("10.48550/arxiv.1804.02767")
    assert r["src"] == "datacite_doi" and r["year"] == 2018
    assert r["surnames"] == ["redmon", "farhadi"]
    assert sim(r["title"], "YOLOv3: An Incremental Improvement") == 1.0


def test_accents_in_surnames():
    from src.verify import norm, surname
    assert norm("Mądry") == "madry" and surname("Piotr Dollár") == "dollar"


def test_checks_use_all_top_candidates():
    c = cit(title="Faster R-CNN: Towards Real-Time Object Detection", first_surname="Ren", year=2015, doi=None)
    cands = [{"src": "crossref", "title": "Faster R-CNN: Towards Real-Time Object Detection",
              "surnames": ["ren"], "year": 2017, "doi": "10.1109/tpami.2016.2577031"},
             {"src": "openalex", "title": "Faster R-CNN: Towards Real-Time Object Detection",
              "surnames": ["ren"], "year": 2015, "doi": None}]
    ev = evidence(c, cands, None, 1)
    assert ev["year_ok"] is True and ev["surname_ok"] is True and ev["n_top"] == 2
