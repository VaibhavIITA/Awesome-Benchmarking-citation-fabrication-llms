from src.verify import Client, evidence, label_at, sim


class Resp:
    def __init__(self, code, data):
        self.status_code, self._d = code, data

    def json(self):
        return self._d

    def raise_for_status(self):
        if self.status_code >= 400:
            raise RuntimeError(self.status_code)


CR_DATA = {"message": {"items": [{"title": ["Fabrication and errors in the bibliographic citations generated by ChatGPT"],
                                   "author": [{"family": "Walters"}, {"family": "Wilder"}],
                                   "issued": {"date-parts": [[2023]]}, "DOI": "10.1038/S41598-023-41032-5"}]}}


def fake_get(url, params=None, timeout=None):
    if "openalex" in url:
        return Resp(200, {"results": []})
    if url.endswith("10.9999/nothing"):
        return Resp(404, None)
    if "/works/10." in url:  # DOI lookup returns a single work
        return Resp(200, {"message": CR_DATA["message"]["items"][0]})
    return Resp(200, CR_DATA)


def cit(**k):
    base = {"citation_id": "x", "title": "Fabrication and errors in the bibliographic citations generated by ChatGPT",
            "authors": "Walters, W. H.", "first_surname": "Walters", "year": 2023,
            "doi": "10.1038/s41598-023-41032-5", "parse_status": "ok"}
    base.update(k)
    return base


def test_sim_identical_and_unrelated():
    assert sim("A B C", "a b c") == 1.0
    assert sim("Deep learning for cats", "Tax law in Ohio") < 0.5


def test_exists(tmp_path):
    cl = Client(tmp_path, get=fake_get, pause=0)
    c = cit()
    ev = evidence(c, cl.crossref(c["title"], c["authors"]) + cl.openalex(c["title"]), cl.by_doi(c["doi"]), 1)
    assert label_at(c, ev, 0.85) == "exists"


def test_wrong_year_is_metadata_error(tmp_path):
    cl = Client(tmp_path, get=fake_get, pause=0)
    c = cit(year=2015, doi=None)
    ev = evidence(c, cl.crossref(c["title"], c["authors"]), None, 1)
    assert label_at(c, ev, 0.85) == "metadata_error"


def test_unresolvable_doi_is_metadata_error(tmp_path):
    cl = Client(tmp_path, get=fake_get, pause=0)
    c = cit(doi="10.9999/nothing")
    ev = evidence(c, cl.crossref(c["title"], c["authors"]), cl.by_doi(c["doi"]), 1)
    assert ev["doi_resolves"] is False
    assert label_at(c, ev, 0.85) == "metadata_error"


