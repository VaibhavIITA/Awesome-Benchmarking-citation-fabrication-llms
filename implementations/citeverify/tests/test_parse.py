from src.parse import first_surname, parse_item, split_items

RESP = """Here are some references:

1. Walters, W. H., & Wilder, E. I. (2023). Fabrication and errors in the bibliographic citations generated by ChatGPT. Scientific Reports, 13, 14045. https://doi.org/10.1038/s41598-023-41032-5
2. **Ji, Z., Lee, N.** (2023). Survey of hallucination in natural language generation. *ACM Computing Surveys*, 55(12).
   DOI: 10.1145/3571730.
3) P. Lewis, E. Perez, "Retrieval-augmented generation for knowledge-intensive NLP tasks," in NeurIPS, 2020.
[4] Smith J. A study of nothing in particular. Journal of Things. 2019.
"""

# Shape seen in the real pilot (17 Nov 2026): numbered items with labelled bullet sub-fields.
LABELLED = """Here are 10 references:

1. **Authors**: Michael Hicks, et al.
   - **Year**: 2017
   - **Title**: The Fuzzing Revolution: Improving Software Quality
   - **Venue**: Communications of the ACM
   - **DOI**: [10.1145/3086750](https://doi.org/10.1145/3086750)

2. Author(s): Chen, X., Shi, J. Year: 2019 Title: A Study of Side Channels Venue: IEEE TC DOI: 10.1109/TC.2019.1 Abstract: We study things.
"""

BULLETS = """- Brown, T. (2020). Language models are few-shot learners. NeurIPS.
- Smith, J. (2019). Another paper title here. Journal of X.
"""


def test_split_counts_items():
    items = split_items(RESP)
    assert len(items) == 4
    assert items[1].endswith("DOI: 10.1145/3571730.")  # continuation line joined


def test_apa_fields():
    r = parse_item(split_items(RESP)[0])
    assert r["year"] == 2023
    assert r["doi"] == "10.1038/s41598-023-41032-5"
    assert r["title"].startswith("Fabrication and errors")
    assert r["first_surname"] == "Walters"
    assert r["parse_status"] == "ok"


def test_doi_trailing_dot_and_markdown():
    r = parse_item(split_items(RESP)[1])
    assert r["doi"] == "10.1145/3571730"
    assert r["first_surname"] == "Ji"
    assert "Survey of hallucination" in r["title"]


def test_ieee_quoted_title():
    r = parse_item(split_items(RESP)[2])
    assert r["title"].startswith("Retrieval-augmented generation")
    assert r["first_surname"] == "Lewis"
    assert r["year"] == 2020


def test_no_paren_year():
    r = parse_item(split_items(RESP)[3])
    assert r["year"] == 2019
    assert r["title"] == "A study of nothing in particular"


def test_garbage_is_fail():
    assert parse_item("ok")["parse_status"] == "fail"


def test_surname_forms():
    assert first_surname("Smith, J., Doe, A.") == "Smith"
    assert first_surname("J. Smith and A. Doe") == "Smith"
    assert first_surname("Smith J et al") == "Smith"
    assert first_surname("P. Lewis, E. Perez") == "Lewis"
    assert first_surname("Smith JA, Doe B") == "Smith"


def test_bullets_are_subfields_when_numbered():
    items = split_items(LABELLED)
    assert len(items) == 2


def test_labelled_fields():
    a, b = [parse_item(x) for x in split_items(LABELLED)]
    assert a["title"] == "The Fuzzing Revolution: Improving Software Quality"
    assert a["year"] == 2017 and a["doi"] == "10.1145/3086750" and a["first_surname"] == "Hicks"
    assert b["title"] == "A Study of Side Channels" and b["year"] == 2019
    assert b["doi"] == "10.1109/tc.2019.1" and b["first_surname"] == "Chen"
    assert a["parse_status"] == b["parse_status"] == "ok"


def test_bullets_only_answer():
    assert len(split_items(BULLETS)) == 2
